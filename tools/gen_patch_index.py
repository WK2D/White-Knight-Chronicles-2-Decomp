"""Generate patches/index.json: one machine-readable record per SDK patch.

    python tools/gen_patch_index.py          # write patches/index.json
    python tools/gen_patch_index.py --check  # exit 1 if the file is out of date

Each record has the patch number, file, a title from the file name, the patch's
own description when it has one, the SDK files it touches, the subsystems those
files belong to, the docs/PATCHES.md note that covers it, if any, and any
docs/FINDINGS.md sections that name it. Run it
after adding a patch or a patch note.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATCHES = ROOT / 'patches'
NOTES = ROOT / 'docs' / 'PATCHES.md'
FINDINGS = ROOT / 'docs' / 'FINDINGS.md'
OUT = PATCHES / 'index.json'

SUBSYSTEMS = [
    (r'^libs/video/|rsx|gcm', 'rendering'),
    (r'^libs/spurs/|^runtime/spu/|spurs|spu_', 'spu'),
    (r'^libs/input/|pad', 'input'),
    (r'^libs/(audio|codec|media)|adec|vdec|dmux|pamf|vpost|audio', 'media'),
    (r'^libs/filesystem/|edat|sdat|vfs', 'filesystem'),
    (r'^runtime/syscalls/|syscall|lv2|sys_', 'kernel'),
    (r'^runtime/ppu/|ppu_', 'ppu'),
    (r'^tests?/|_test\.|/tests?/', 'tests'),
]


def slug(text):
    t = re.sub(r'[^\w\- ]', '', text.strip().lower())
    return t.replace(' ', '-')


def note_ranges(path=NOTES):
    """(first, last, heading) for every section of `path` naming patch numbers."""
    out = []
    if not path.exists():
        return out
    for line in path.read_text(encoding='utf-8').split('\n'):
        if not line.startswith('## '):
            continue
        title = line[3:]
        m = re.search(r'patch(?:es)? (\d{4})(?:-(\d{4}))?', title)
        if m:
            first = int(m[1])
            out.append((first, int(m[2]) if m[2] else first, title))
    return out


def classify(files):
    tags = []
    for path in files:
        for pattern, tag in SUBSYSTEMS:
            if re.search(pattern, path, re.I) and tag not in tags:
                tags.append(tag)
    return tags or ['other']


def build():
    ranges = note_ranges()
    found = note_ranges(FINDINGS)
    records = []
    for p in sorted(PATCHES.glob('[0-9][0-9][0-9][0-9]-*.patch')):
        text = p.read_text(encoding='utf-8', errors='replace')
        number = int(p.name[:4])
        head = text.split('diff --git', 1)[0].strip()
        files = sorted(set(re.findall(r'^diff --git a/(\S+) b/', text, re.M)))
        notes = [f'docs/PATCHES.md#{slug(t)}' for a, b, t in ranges if a <= number <= b]
        if not notes and ranges and number < min(a for a, _, _ in ranges):
            # Older patches are described together in the history section.
            notes = ['docs/PATCHES.md#earlier-runtime-fixes-and-validation-history']
        records.append({
            'number': number,
            'file': f'patches/{p.name}',
            'title': p.stem[5:].replace('-', ' '),
            'description': ' '.join(head.split()) if head else None,
            'files': files,
            'subsystems': classify(files),
            'note': notes[0] if notes else None,
            'findings': [f'docs/FINDINGS.md#{slug(t)}' for a, b, t in found if a <= number <= b],
        })
    return {
        'about': 'Generated by tools/gen_patch_index.py from patches/ and docs/PATCHES.md. Do not edit by hand.',
        'patch_count': len(records),
        'patches': records,
    }


def main():
    text = json.dumps(build(), indent=2) + '\n'
    if '--check' in sys.argv:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if current != text:
            print('patches/index.json is out of date; run python tools/gen_patch_index.py')
            return 1
        print('patches/index.json is up to date')
        return 0
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)} with {text.count(chr(34) + "number" + chr(34))} patches')
    return 0


if __name__ == '__main__':
    sys.exit(main())
